/// The font on the GPU: every glyph side by side in one white texture, tinted when drawn.
pub struct Font {
    tex: TexId,
}

impl Font {
    pub fn new(gpu: &Gpu, batch: &mut SpriteBatch) -> Font {
        let w = GLYPHS.len() * GLYPH_W;
        let mut rgba = vec![0u8; w * GLYPH_H * 4];
        for (g, (_, rows)) in GLYPHS.iter().enumerate() {
            for (y, row) in rows.iter().enumerate() {
                for (x, c) in row.bytes().enumerate() {
                    if c == b'#' {
                        let i = (y * w + g * GLYPH_W + x) * 4;
                        rgba[i..i + 4].copy_from_slice(&[255; 4]);
                    }
                }
            }
        }
        Font { tex: batch.texture(gpu, w as u32, GLYPH_H as u32, &rgba) }
    }

    /// Width of `text` in pixels at `scale` (whole numbers keep the pixels square).
    pub fn width(text: &str, scale: f32) -> f32 {
        let n = text.chars().count() as f32;
        if n == 0.0 { 0.0 } else { (n * ADVANCE - 1.0) * scale }
    }

    /// Height of a line at `scale`.
    pub fn height(scale: f32) -> f32 {
        GLYPH_H as f32 * scale
    }

    /// Draw `text` with its top left at (x, y), rounded to whole pixels; returns its width.
    pub fn draw(&self, batch: &mut SpriteBatch, text: &str, x: f32, y: f32, scale: f32, colour: [u8; 4]) -> f32 {
        // Whole pixels, so no glyph column falls between two screen pixels.
        let (mut cx, y) = (x.round(), y.round());
        for c in text.chars() {
            let c = c.to_ascii_uppercase();
            let g = GLYPHS.iter().position(|(k, _)| *k == c).or_else(|| GLYPHS.iter().position(|(k, _)| *k == '?'));
            if let Some(g) = g
                && c != ' '
            {
                let src = Rect::new((g * GLYPH_W) as f32, 0.0, GLYPH_W as f32, GLYPH_H as f32);
                let dst = Rect::new(cx, y, GLYPH_W as f32 * scale, GLYPH_H as f32 * scale);
                batch.sprite(self.tex, src, dst, colour);
            }
            cx += ADVANCE * scale;
        }
        Font::width(text, scale)
    }
}
